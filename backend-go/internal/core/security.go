// Argon2id defaults matching argon2-cffi 23.1.0 PasswordHasher() defaults:
// time_cost=3, memory_cost=65536 (64 MiB), parallelism=4, hash_len=32, salt_len=16
const (
	argonTime    uint32 = 3
	argonMemory  uint32 = 65536
	argonThreads uint8  = 4
	argonKeyLen  uint32 = 32
	argonSaltLen int    = 16
)

func HashPassword(password string) (string, error) {
	salt := make([]byte, argonSaltLen)
	if _, err := rand.Read(salt); err != nil {
		return "", err
	}
	hash := argon2.IDKey([]byte(password), salt, argonTime, argonMemory, argonThreads, argonKeyLen)
	b64Salt := base64.RawStdEncoding.EncodeToString(salt)
	b64Hash := base64.RawStdEncoding.EncodeToString(hash)
	return fmt.Sprintf("$argon2id$v=%d$m=%d,t=%d,p=%d$%s$%s",
		argon2.Version, argonMemory, argonTime, argonThreads, b64Salt, b64Hash), nil
}

// VerifyPassword verifies a plaintext password against a PHC-formatted Argon2id or Argon2i hash string.
// Fully compatible with existing hashes generated by Python's argon2-cffi library.
func VerifyPassword(password, encodedHash string) bool {
	if encodedHash == "" {
		return false
	}
	parts := strings.Split(encodedHash, "$")
	if len(parts) != 6 {
		return false
	}
	variant := parts[1]
	if variant != "argon2id" && variant != "argon2i" {
		return false
	}
	var memory, timeCost uint32
	var threads uint8
	_, err := fmt.Sscanf(parts[3], "m=%d,t=%d,p=%d", &memory, &timeCost, &threads)
	if err != nil || memory == 0 || timeCost == 0 || threads == 0 {
		return false
	}
	salt, err := base64.RawStdEncoding.DecodeString(parts[4])
	if err != nil {
		return false
	}
	expectedHash, err := base64.RawStdEncoding.DecodeString(parts[5])
	if err != nil || len(expectedHash) == 0 {
		return false
	}
	keyLen := uint32(len(expectedHash))
	var computed []byte
	if variant == "argon2i" {
		computed = argon2.Key([]byte(password), salt, timeCost, memory, threads, keyLen)
	} else {
		computed = argon2.IDKey([]byte(password), salt, timeCost, memory, threads, keyLen)
	}
	return subtle.ConstantTimeCompare(computed, expectedHash) == 1
}

func CreateAccessToken(cfg *config.Settings, subject string, extra map[string]any, expireMinutes *int) (string, error) {
	now := time.Now().UTC()
	minutes := cfg.AccessTokenExpireMinutes
	if expireMinutes != nil {
		minutes = *expireMinutes
	}
	claims := jwt.MapClaims{
		"sub":  subject,
		"type": "access",
		"iat":  now.Unix(),
		"exp":  now.Add(time.Duration(minutes) * time.Minute).Unix(),
		"jti":  uuid.NewString(),
	}
	for k, v := range extra {
		claims[k] = v
	}
	token := jwt.NewWithClaims(jwt.SigningMethodHS256, claims)
	return token.SignedString([]byte(cfg.JWTSecret))
}

var (
	ErrTokenExpired = errors.New("token_expired")
	ErrTokenInvalid = errors.New("invalid_token")
)

func DecodeAccessToken(cfg *config.Settings, tokenStr string) (jwt.MapClaims, error) {
	token, err := jwt.Parse(tokenStr, func(t *jwt.Token) (any, error) {
		if t.Method.Alg() != jwt.SigningMethodHS256.Alg() {
			return nil, ErrTokenInvalid
		}
		return []byte(cfg.JWTSecret), nil
	}, jwt.WithValidMethods([]string{"HS256"}))
	if err != nil {
		if errors.Is(err, jwt.ErrTokenExpired) {
			return nil, ErrTokenExpired
		}
		return nil, ErrTokenInvalid
	}
	claims, ok := token.Claims.(jwt.MapClaims)
	if !ok || !token.Valid {
		return nil, ErrTokenInvalid
	}
	return claims, nil
}

func CreateRefreshTokenValue() string {
	return uuid.NewString() + uuid.NewString()
}

func HashToken(raw string) string {
	sum := sha256.Sum256([]byte(raw))
	return hex.EncodeToString(sum[:])
}
